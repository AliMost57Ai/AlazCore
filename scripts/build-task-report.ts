workbook.created = new Date();

function addSheet(
  name: string,
  title: string,
  headers: string[],
  rows: (string | number)[][],
  widths: number[]
): void {
  const sheet = workbook.addWorksheet(name, {
    views: [{ rightToLeft: true, state: 'frozen', ySplit: 3 }],
    pageSetup: { orientation: 'landscape', fitToPage: true },
  });
  sheet.addRow([title]);
  sheet.mergeCells(1, 1, 1, headers.length);
  const titleCell = sheet.getCell(1, 1);
  titleCell.font = { bold: true, size: 14, color: { argb: 'FFFB7401' } };
  sheet.addRow([
    `سامانه AlazCore — گزارش کامل کارهای تسک SuperAdmin/Core — ${new Date().toLocaleDateString('fa-IR-u-ca-persian')}`,
  ]);
  sheet.mergeCells(2, 1, 2, headers.length);
  sheet.getCell(2, 1).font = { size: 10, color: { argb: 'FF6B7B84' } };
  sheet.addRow([]);
  const headerRow = sheet.addRow(headers);
  headerRow.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  headerRow.eachCell((cell) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1B2A34' } };
    cell.alignment = { horizontal: 'center', vertical: 'middle' };
    cell.border = {
      top: { style: 'thin' },
      left: { style: 'thin' },
      bottom: { style: 'thin' },
      right: { style: 'thin' },
    };
  });
  for (const row of rows) {
    sheet.addRow(row);
  }
  for (let i = 5; i <= sheet.rowCount; i += 1) {
    sheet.getRow(i).eachCell((cell) => {
      cell.alignment = { vertical: 'top', wrapText: true };
      cell.border = {
        top: { style: 'hair' },
        left: { style: 'hair' },
        bottom: { style: 'hair' },
        right: { style: 'hair' },
      };
    });
    if ((i - 5) % 2 === 1) {
      sheet.getRow(i).eachCell((cell) => {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF4F7F8' } };
      });
    }
  }
  headers.forEach((_, index) => {
    sheet.getColumn(index + 1).width = widths[index] ?? 20;
  });
}

